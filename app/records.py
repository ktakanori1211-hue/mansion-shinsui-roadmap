def find(label: str) -> Optional[dict]:
    """町丁の記録を返す。手元の表に入れていない町丁は None で、未確認として扱う。"""
    text = normalize_address(label)
    for record in _RECORDS:
        if record["city"] in text and re.search(record["town"], text):
            return record
    return None
